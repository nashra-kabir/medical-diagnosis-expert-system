# MEDICAL DIAGNOSIS EXPERT SYSTEM
# Initial AI Project Prototype

# 1. KNOWLEDGE BASE
# Store patient symptoms as facts.

patient_data = {
    "patient_1": ["fever", "cough", "sore_throat"]
}


# 2. INFERENCE RULES
# These are educational symptom patterns,
# not clinically validated diagnosis rules.

def analyze_patient(patient_id):

    symptoms = patient_data.get(patient_id, [])

    possible_patterns = []

    # Rule 1
    if "cough" in symptoms and "sore_throat" in symptoms:
        possible_patterns.append({
            "pattern": "Respiratory symptom pattern",
            "reason": "Patient has cough and sore throat."
        })

    # Rule 2
    if "fever" in symptoms and "headache" in symptoms:
        possible_patterns.append({
            "pattern": "Fever with headache pattern",
            "reason": "Patient has fever and headache."
        })

    return possible_patterns


# 3. RUN THE EXPERT SYSTEM

patient_id = "patient_1"

print("MEDICAL DIAGNOSIS EXPERT SYSTEM")
print("--------------------------------")

print("Patient symptoms:", patient_data[patient_id])

results = analyze_patient(patient_id)

if results:
    print("\nPossible symptom patterns:")

    for result in results:
        print("Pattern:", result["pattern"])
        print("Reason:", result["reason"])
else:
    print("\nNo matching symptom patterns found.")

print("\nNote: This is an educational prototype,")
print("not a medical diagnosis.")

# TESTING WITH A SECOND PATIENT

patient_data["patient_2"] = ["fever", "headache"]

print("Testing Patient 2:")

results = analyze_patient("patient_2")

for result in results:
    print("Pattern:", result["pattern"])
    print("Reason:", result["reason"])

#  USER INPUT MODULE

